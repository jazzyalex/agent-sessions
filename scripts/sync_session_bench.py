#!/usr/bin/env python3
"""Import Session-Bench's generated leaderboard for the hosted Pages view.

The benchmark is owned by https://github.com/jazzyalex/session-bench. Agent
Sessions checks in an exact copy of its generated leaderboard because GitHub
Pages builds this repository without fetching another repository at deploy
time.

Usage:
  python3 scripts/sync_session_bench.py \
      /path/to/session-bench/data/leaderboard.yml
  python3 scripts/sync_session_bench.py \
      /path/to/session-bench/data/leaderboard.yml --check
"""
from __future__ import annotations

import argparse
from pathlib import Path


REPO = Path(__file__).resolve().parent.parent
DEFAULT_TARGET = REPO / "docs" / "_data" / "session_bench.yml"
REQUIRED_MARKERS = (
    "# GENERATED by scripts/evaluate.py — do not hand-edit.\n",
    "# Inputs: data/measurements.json + data/verdicts.yml.\n",
    "generated_by: scripts/evaluate.py\n",
    "source_repository: https://github.com/jazzyalex/session-bench\n",
)


def validate_source(raw: bytes) -> None:
    try:
        text = raw.decode("utf-8")
    except UnicodeDecodeError as exc:
        raise SystemExit(f"source is not UTF-8: {exc}") from exc
    missing = [marker.rstrip() for marker in REQUIRED_MARKERS if marker not in text]
    if missing:
        raise SystemExit("source is not the canonical Session-Bench artifact; missing: "
                         + ", ".join(missing))


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("source", type=Path,
                        help="session-bench/data/leaderboard.yml")
    parser.add_argument("--target", type=Path, default=DEFAULT_TARGET)
    parser.add_argument("--check", action="store_true",
                        help="fail unless the checked-in artifact is byte-identical")
    args = parser.parse_args()

    raw = args.source.read_bytes()
    validate_source(raw)

    if args.check:
        if not args.target.exists() or args.target.read_bytes() != raw:
            raise SystemExit(f"hosted artifact is stale: {args.target}")
        print(f"OK: {args.target} is byte-identical to {args.source}")
        return 0

    args.target.parent.mkdir(parents=True, exist_ok=True)
    temporary = args.target.with_name(args.target.name + ".tmp")
    temporary.write_bytes(raw)
    temporary.replace(args.target)
    print(f"Updated {args.target} from {args.source}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
